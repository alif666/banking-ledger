CREATE TABLE currency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency_code VARCHAR(3) NOT NULL UNIQUE
);

CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(34) NOT NULL UNIQUE,
    currency_id BIGINT NOT NULL,
    balance NUMERIC(19, 4) NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    user_id BIGINT NOT NULL,
    account_type VARCHAR(30) NOT NULL,

    CONSTRAINT chk_account_balance_non_negative CHECK (balance >= 0),
    CONSTRAINT fk_account_currency FOREIGN KEY (currency_id)
        REFERENCES currency (id) ON DELETE RESTRICT,
    CONSTRAINT fk_account_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT
);

CREATE TABLE money_transfer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id UUID NOT NULL UNIQUE,
    from_account_id BIGINT NOT NULL,
    to_account_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount_to_transfer NUMERIC(19, 4) NOT NULL,

    CONSTRAINT chk_transfer_amount_positive CHECK (amount_to_transfer > 0),
    CONSTRAINT chk_transfer_distinct_accounts CHECK (from_account_id <> to_account_id),
    CONSTRAINT chk_transfer_status CHECK (status IN ('SUCCESS', 'FAILURE')),
    CONSTRAINT fk_transfer_from_account FOREIGN KEY (from_account_id)
        REFERENCES account (id) ON DELETE RESTRICT,
    CONSTRAINT fk_transfer_to_account FOREIGN KEY (to_account_id)
        REFERENCES account (id) ON DELETE RESTRICT
);

CREATE TABLE ledger_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,
    transfer_amount NUMERIC(19, 4) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_ledger_entry_amount_non_zero CHECK (transfer_amount <> 0),
    CONSTRAINT fk_ledger_entry_transfer FOREIGN KEY (transfer_id)
        REFERENCES money_transfer (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ledger_entry_account FOREIGN KEY (account_id)
        REFERENCES account (id) ON DELETE RESTRICT
);

